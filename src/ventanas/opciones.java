    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
       Expediente aux = new Expediente();
       int indice =-1;
       
       int id1= Integer.parseInt(jTextField1.getText());
        for (int i = 1; i <= Listaexp.longitud(); i++) {
            if (id1==Listaexp.iesimo(i).getId()) {
                aux=Listaexp.iesimo(i);
                indice=i;
            }
        }
        for (int i = 1; i <= Listadep.longitud(); i++) {
            Cola<Expediente> aux2 = new Cola();
            while(!Listadep.iesimo(i).getColaexp().esVacia()){
                Expediente aux3 = Listadep.iesimo(i).getColaexp().desencolar();
                if(aux3.getId()!=Integer.parseInt(jTextField1.getText())){
                    aux2.encolar(aux3);
                }
            }
            Listadep.iesimo(i).setColaexp(aux2);
        }
        
        for (int i = 1; i <= Listadep.longitud(); i++) {
            if (jComboBox1.getSelectedItem().equals(Listadep.iesimo(i).getNombre()) && indice!=-1 && !Listadep.esVacia()) {
                String Nombre = String.valueOf(jComboBox1.getSelectedItem());
                colocarmov(aux,Nombre);
                Listadep.iesimo(i).getColaexp().encolar(aux);
                
                
            }
        }
        if (indice==-1) {
            JOptionPane.showMessageDialog(this, "no existe tal expediente");
        }
        
    }//GEN-LAST:event_jButton5ActionPerformed

