    public void ordenarPorPrioridad(Lista<Expediente> lista) {
    if (lista.getCabeza() == null || lista.getCabeza().getSgteNodo() == null) return;

    boolean cambiado;

    do {
        Nodo<Expediente> actual = lista.getCabeza();
        Nodo<Expediente> anterior = null;
        cambiado = false;

        while (actual != null && actual.getSgteNodo() != null) {
            Nodo<Expediente> siguiente = actual.getSgteNodo();
            if (actual.getItem().getPrioridad() > siguiente.getItem().getPrioridad()) {  
                if (anterior == null) {                   
                    lista.setCabeza(siguiente);
                } else {
                    anterior.setSgteNodo(siguiente);
                }
                actual.setSgteNodo(siguiente.getSgteNodo());
                siguiente.setSgteNodo(actual);

                anterior = siguiente;
                cambiado = true;
            } else {
                anterior = actual;
                actual = actual.getSgteNodo();
            }
        }
    } while (cambiado);
}
    public void alerta(){
        if (!Listaexp.esVacia()) {
        int prioritario = 99999;
        Expediente prio = new Expediente();
        Expediente antiguo = new Expediente();
        LocalDateTime Antiguo = LocalDateTime.now();
        for (int i = 1; i <= Listaexp.longitud(); i++) {
            if(Listaexp.iesimo(i).getPrioridad()<prioritario && Listaexp.iesimo(i).getSeguimiento().getCabeza()==null){
               prioritario=Listaexp.iesimo(i).getPrioridad(); 
               prio=Listaexp.iesimo(i);
            }
            
        }
        for (int i = 1; i <= Listaexp.longitud(); i++) {
            if(Listaexp.iesimo(i).getFechaInicio().isBefore(Antiguo) && Listaexp.iesimo(i).getSeguimiento().getCabeza()==null){
               antiguo=Listaexp.iesimo(i); 
               Antiguo=Listaexp.iesimo(i).getFechaInicio();
            }
            
        }
        
        JOptionPane.showMessageDialog(this, "Expediente más prioritario sin atender: "+prio.getId() + "\n Expediente más antiguo sin atender: " + antiguo.getId()); 
        }
        
    }

